"""Hallway navigation POMDP (Cassandra 1998 / Littman, Cassandra & Kaelbling 1995).

Exact specification loaded from Anthony Cassandra's canonical POMDP file
(hallway.POMDP, retrieved from pomdp.org).  The file comment reads:
    "POMDP file for the following grid world [...] Navigation problem from
     Littman, Cassandra and Kaelbling's ML-95 paper"
and is also listed in Cassandra's PhD thesis as "Hallway (57 state navigation
problem" — the discrepancy between "57" and "60" arises because 57 refers to
*non-goal* or *non-terminal* states in some formulations; the file itself
declares ``states: 60``.

Specification summary
---------------------
- 60 hidden states: position × orientation over a hallway layout.
  States 0–55 are navigable; states 56–59 are absorbing reset states
  that the environment enters after reaching the goal (states 10, 18, 26, 34
  are the four named goal positions each with a unique identifying observation).
- 5 actions: 0=stay, 1=forward, 2=turn-right, 3=turn-left, 4=u-turn.
- 21 observations: 16 wall-pattern observations (bits for walls N/E/S/W),
  4 goal-identifier observations (one per named goal), and 1 reset observation.
- Discount: 0.95 (per Cassandra file).
- Reward: +1.0 on every step whose *next* state is one of {56,57,58,59}
  (the absorbing goal states); 0.0 otherwise.  This matches the
  ``R: * : * : 56 : * 1.0`` ... ``R: * : * : 59 : * 1.0`` lines.
- Start: uniform over states 0–55 (states 56–59 start with prob 0).

Belief-partition size from prior work
--------------------------------------
Roy & Gordon (2003, "Exponential Family PCA for Belief Compression in POMDPs",
NIPS) apply exponential-family PCA to Hallway and report that 10–20 compressed
belief dimensions suffice to approximate the full belief (Table 2 of their
paper).  The exact number of *distinct* belief clusters depends on planning
horizon and compression threshold.  The widely-cited figure is approximately
20 distinguishable belief clusters under a 2D PCA projection (their Figure 2).
Subsequent work (e.g. Porta et al. 2006, "Point-Based Value Iteration for
Continuous POMDPs") treats Hallway as having an effective belief-state
complexity of order ~20 for near-optimal policy computation.  We therefore
treat 20 as the published reference figure for the belief-partition size.

Our learned quotient (model-free, continuation-distribution equivalence) may
differ from the belief-partition count because:
  1. We use a single exploration policy, not the supremum over controllers.
  2. Continuation-distribution equivalence at finite window k may merge
     belief states that differ only in deep-future structure.
  3. Uniform random exploration may under-cover sparse regions.

Usage
-----
    from environments.layer1_discrete.hallway import HallwayPOMDP
    env = HallwayPOMDP(seed=42)
    obs = env.reset()
    result = env.step(1)  # forward

Source
------
Cassandra, A. R. (1998). *Exact and Approximate Algorithms for Partially
Observable Markov Decision Processes*. PhD thesis, Brown University.
Littman, M. L., Cassandra, A. R., & Kaelbling, L. P. (1995). Learning
Policies for Partially Observable Environments: Scaling Up. *ICML-95*.
Roy, N. & Gordon, G. (2003). Exponential Family PCA for Belief Compression
in POMDPs. *NIPS*.
"""

