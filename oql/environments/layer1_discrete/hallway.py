def _build_matrices() -> tuple[np.ndarray, np.ndarray]:
    T = np.zeros((_N_ACTIONS, _N_STATES, _N_STATES), dtype=np.float64)
    for a, s, s2_list, p_list in _T_SPARSE:
        for s2, p in zip(s2_list, p_list):
            T[a, s, s2] = p
    O = np.array(_O_ROWS, dtype=np.float64)
    return T, O


_T_MATRIX, _O_MATRIX = _build_matrices()

# Start distribution: uniform over states 0–55.
_START_PROBS: np.ndarray = np.array(
    [0.017865] + [0.017857] * 55 + [0.0] * 4, dtype=np.float64
)
_START_PROBS /= _START_PROBS.sum()  # normalise exactly to 1


class HallwayPOMDP(POMDPEnvironment):
    """Hallway navigation POMDP (Cassandra 1998).

    Spec: 60 states, 5 actions, 21 observations, discount 0.95.
    Reward: +1 when next state is one of {56,57,58,59}.
    Reaching a reward state resets the episode (absorbing with restart).

    Parameters
    ----------
    seed:
        Optional RNG seed.
    episodic:
        If True (default), the environment emits ``terminated=True``
        when transitioning into a goal/reset state (56–59) so that the
        trajectory-collection layer starts a new episode.  If False the
        episode continues past the reset (for infinite-horizon experiments).
    """

    def __init__(self, seed: int | None = None, episodic: bool = True):
        self._rng = np.random.default_rng(seed)
        self._state: int = 0
        self._episodic = episodic

    # ------------------------------------------------------------------
    # POMDPEnvironment interface
    # ------------------------------------------------------------------

    @property
    def n_observations(self) -> int:
        return _N_OBS  # 21

    @property
    def n_actions(self) -> int:
        return _N_ACTIONS  # 5

    @property
    def environment_id(self) -> str:
        return "HallwayPOMDP(Cassandra1998)"

    @property
    def metadata(self) -> dict[str, object]:
        return {
            # No single agreed ground-truth quotient size from model-free view.
            # Roy & Gordon (2003) report ~20 belief clusters for Hallway.
            "belief_partition_reference": 20,
            "belief_partition_source": "Roy & Gordon 2003 (NIPS)",
            "n_states": _N_STATES,
            "n_actions": _N_ACTIONS,
            "n_observations": _N_OBS,
            "discount": 0.95,
            "source": "Cassandra 1998 (hallway.POMDP from pomdp.org)",
        }

    def reset(self, seed: int | None = None) -> int:
        if seed is not None:
            self._rng = np.random.default_rng(seed)
        self._state = int(
            self._rng.choice(_N_STATES, p=_START_PROBS)
        )
        return self._emit()

    def step(self, action: int) -> StepResult:
        if not 0 <= action < _N_ACTIONS:
            raise ValueError(f"action must be in [0, {_N_ACTIONS}), got {action}")

        # Sample next state.
        probs = _T_MATRIX[action, self._state]
        next_state = int(self._rng.choice(_N_STATES, p=probs))
        self._state = next_state

        # Reward: +1 iff we landed in a goal state.
        reward = 1.0 if next_state in _GOAL_STATES else 0.0

        # Termination: episodic mode terminates at goal states.
        terminated = self._episodic and (next_state in _GOAL_STATES)

        obs = self._emit()
        return StepResult(
            observation=obs,
            reward=reward,
            terminated=terminated,
            truncated=False,
        )

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _emit(self) -> int:
        """Sample an observation from the current state."""
        probs = _O_MATRIX[self._state]
        return int(self._rng.choice(_N_OBS, p=probs))
